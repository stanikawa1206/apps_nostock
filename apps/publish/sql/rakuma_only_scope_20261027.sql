-- ラクマ専用化（2026-10-27）
-- 目的: ラクマ候補Excelで追加したブランド・グループ所属をラクマの出品対象だけに使い、
--       メルカリ・メルカリshops の presets_lookup を増やさない。
-- 前提: vendor_brand_map_20261027.sql → ebay_account_excluded_vendors_20261027.sql
--       → rakuma_brand_import_20261027.sql を適用済み。
--
-- 考え方:
--   presets_brand.brand_id（メルカリの採番）は共通ブランドIDとして使うだけで、
--   「メルカリで探すか」は vendor_brand_map の有効行（is_active=1）があるかで決まる。
--   (1) 新規ブランド: メルカリ行を is_active=0 にする（IDは記録として残す）。
--   (2) 既存ブランドに足したグループ所属: ブランド自体はメルカリでも使うので、
--       mst.brand_category_group_vendors で所属をラクマだけに絞る。
--       行が無い所属は従来どおり全仕入先共通。

IF OBJECT_ID(N'mst.brand_category_group_vendors', N'U') IS NULL
BEGIN
    CREATE TABLE mst.brand_category_group_vendors (
        brand_id       int          NOT NULL,
        category_group varchar(50)  COLLATE Japanese_CI_AS NOT NULL,
        vendor_name    varchar(50)  COLLATE Japanese_CI_AS NOT NULL,  -- vendor_group（採番体系: メルカリ/ラクマ…）
        note           nvarchar(400) NULL,
        created_at     datetime     NOT NULL CONSTRAINT DF_brand_category_group_vendors_created_at DEFAULT (getdate()),
        CONSTRAINT PK_brand_category_group_vendors PRIMARY KEY (brand_id, category_group, vendor_name),
        CONSTRAINT FK_brand_category_group_vendors_bcg FOREIGN KEY (brand_id, category_group)
            REFERENCES mst.brand_category_groups (brand_id, category_group) ON DELETE CASCADE
    );
END
GO

